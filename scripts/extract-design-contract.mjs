#!/usr/bin/env node
/**
 * extract-design-contract.mjs — freeze the design contract into a versioned file.
 *
 * WHY THIS EXISTS: the design bundle is git-ignored (it is a large extracted working copy — see
 * .gitignore and Impl PRD §0.1), so CI cannot see `handoff/tokens.json` or the Sage & Gold
 * `.dc.html`. Without this, the fidelity gate simply cannot run in the cloud, which is the only
 * place we build.
 *
 * So the *contract itself* — a few KB of colours, scales, the type ramp and the contrast audit —
 * is extracted here and committed to `design/design-contract.json`. The bundle stays ignored; the
 * contract is versioned, reviewable in a diff, and available to CI.
 *
 * Run this whenever the design bundle changes:
 *     node scripts/extract-design-contract.mjs
 *
 * `check-design-fidelity.mjs` then reads the committed contract — and, whenever the bundle *is*
 * present (i.e. on this machine), re-derives it and fails if the committed copy has gone stale.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { argv, exit } from 'node:process';
import { pathToFileURL } from 'node:url';

const ROOT = argv[2] ?? '.';
const BUNDLE = `${ROOT}/Design System/Final Designs/vastufirst-mobile-apps-implementation/project`;
const TOKENS = `${BUNDLE}/handoff/tokens.json`;
const DS = `${BUNDLE}/VastuFirst - Sage & Gold Design System.dc.html`;

export function deriveContract(root = '.') {
  const bundle = `${root}/Design System/Final Designs/vastufirst-mobile-apps-implementation/project`;
  const tokensPath = `${bundle}/handoff/tokens.json`;
  const dsPath = `${bundle}/VastuFirst - Sage & Gold Design System.dc.html`;
  if (!existsSync(tokensPath) || !existsSync(dsPath)) return null;

  const tokens = JSON.parse(readFileSync(tokensPath, 'utf8'));
  const html = readFileSync(dsPath, 'utf8');

  // type ramp — `const ramp=[{name:'display',fam:'Marcellus',size:34,weight:400,lh:'1.2',tr:'0',…}]`
  const ramp = [];
  const rampBlock = html.match(/const ramp=\[([\s\S]*?)\]\.map/);
  if (rampBlock) {
    for (const m of rampBlock[1].matchAll(
      /\{name:'([^']+)',fam:'([^']+)',size:(\d+),weight:(\d+),lh:'([^']+)',tr:'([^']+)'/g,
    )) {
      ramp.push({
        name: m[1], family: m[2], size: +m[3], weight: +m[4],
        lineHeight: parseFloat(m[5]),
        tracking: m[6] === '0' ? 0 : parseFloat(m[6]),
      });
    }
  }

  // the design's own accessibility audit — `['text-primary','color-paper',c.ink,P,4.5,'Body…']`
  const contrast = [];
  const auditBlock = html.match(/const auditRows=\[([\s\S]*?)\]\.map/);
  if (auditBlock) {
    for (const m of auditBlock[1].matchAll(/\['([^']+)','([^']+)',[^,]+,[^,]+,([\d.]+),'([^']*)'\]/g)) {
      contrast.push({ fg: m[1], bg: m[2], floor: parseFloat(m[3]), use: m[4] });
    }
  }

  return {
    $comment:
      'GENERATED by scripts/extract-design-contract.mjs from the git-ignored design bundle. ' +
      'Do not hand-edit — change the design, then re-run the extractor.',
    source: 'Sage & Gold design system (handoff/tokens.json + the .dc.html ramp and contrast audit)',
    color: tokens.color,
    space: tokens.space,
    radius: tokens.radius,
    elevation: tokens.elevation,
    border: tokens.border,
    ramp,
    contrast,
  };
}

// -- CLI ----------------------------------------------------------------------------------------
// Only run when invoked directly; check-design-fidelity.mjs imports deriveContract() from here.
const invokedDirectly = argv[1] && import.meta.url === pathToFileURL(argv[1]).href;
if (invokedDirectly) {
  if (!existsSync(TOKENS) || !existsSync(DS)) {
    console.error('extract-design-contract: the design bundle is not present.');
    console.error(`  expected: ${TOKENS}`);
    console.error('  Extract "VastuFirst Mobile Apps Implementation-handoff.zip" first (Impl PRD §0.1).');
    exit(2);
  }
  const contract = deriveContract(ROOT);
  mkdirSync(`${ROOT}/design`, { recursive: true });
  const out = `${ROOT}/design/design-contract.json`;
  writeFileSync(out, JSON.stringify(contract, null, 2) + '\n', 'utf8');
  console.log(`wrote ${out}`);
  console.log(
    `  ${Object.keys(contract.color).length} colours · ${Object.keys(contract.space).length} spacings · ` +
    `${Object.keys(contract.radius).length} radii · ${Object.keys(contract.elevation).length} elevations · ` +
    `${Object.keys(contract.border).length} borders · ${contract.ramp.length} type styles · ` +
    `${contract.contrast.length} contrast pairs`,
  );
}
