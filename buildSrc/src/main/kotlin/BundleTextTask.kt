import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Turns a resources folder's text files into one Kotlin source file holding them as strings.
 *
 * ⭐ WHY (iPhone plan, stage 1): on Android and the JVM the rule files, the reader's recipe and the
 * recorded plan readings are read off the classpath. An iPhone has no classpath, and Kotlin/Native
 * tests do not copy resources next to the test binary. So for the iPhone the same files are compiled
 * INTO the code, from the very same folder — there is no second copy to drift. Only .json and .txt are
 * taken; pictures stay JVM-only.
 *
 * The output is `internal val <mapName>: Map<String, String>`, keyed exactly like a classpath path
 * ("/ruleset/rooms.json"), so the iPhone lookup and the JVM lookup take the same argument.
 */
abstract class BundleTextTask : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sourceDir: DirectoryProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val mapName: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val root = sourceDir.get().asFile
        val files = root.walkTopDown()
            .filter { it.isFile && (it.extension == "json" || it.extension == "txt") }
            .sortedBy { it.relativeTo(root).invariantSeparatorsPath }
            .toList()
        val out = StringBuilder()
        out.append("// GENERATED by BundleTextTask from ").append(root.name).append(" — do not edit.\n")
        out.append("package ").append(packageName.get()).append("\n\n")
        out.append("internal val ").append(mapName.get()).append(": Map<String, String> = mapOf(\n")
        for (f in files) {
            val key = "/" + f.relativeTo(root).invariantSeparatorsPath
            out.append("    ").append(literal(key)).append(" to listOf(\n")
            // Chunked so no single literal grows unbounded; joined back exactly.
            chunks(f.readText(Charsets.UTF_8)).forEach { out.append("        ").append(literal(it)).append(",\n") }
            out.append("    ).joinToString(\"\"),\n")
        }
        out.append(")\n")
        val dir = outputDir.get().asFile
        dir.deleteRecursively()
        val target = dir.resolve(packageName.get().replace('.', '/')).resolve(mapName.get().replaceFirstChar { it.uppercase() } + ".kt")
        target.parentFile.mkdirs()
        target.writeText(out.toString(), Charsets.UTF_8)
    }

    /** ~4,000-character pieces that never split an emoji's two halves (a lone half cannot be written as UTF-8). */
    private fun chunks(text: String): List<String> {
        val parts = mutableListOf<String>()
        var start = 0
        while (start < text.length) {
            var end = minOf(start + 4000, text.length)
            if (end < text.length && text[end - 1].isHighSurrogate()) end -= 1
            parts += text.substring(start, end)
            start = end
        }
        return parts
    }

    private fun literal(s: String): String = buildString {
        append('"')
        for (c in s) when (c) {
            BACKSLASH -> append(BACKSLASH).append(BACKSLASH)
            '"' -> append(BACKSLASH).append('"')
            '$' -> append(BACKSLASH).append('$')
            '\n' -> append(BACKSLASH).append('n')
            '\r' -> append(BACKSLASH).append('r')
            '\t' -> append(BACKSLASH).append('t')
            else -> if (c.code < 0x20) append(BACKSLASH).append('u').append(c.code.toString(16).padStart(4, '0')) else append(c)
        }
        append('"')
    }

    private companion object {
        // Written as a char code so no shell or editor can eat it on the way into this file.
        val BACKSLASH: Char = 92.toChar()
    }
}
